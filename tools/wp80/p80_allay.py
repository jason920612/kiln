"""wp80 item 3: allay dancing to a jukebox and duplicating with an amethyst shard (real client, one actor per server: par.sh p80_allay.py)."""
from p72 import *
a = C(int(os.environ.get("KILN_AGENT_PORT", "25999")))
ME = "KilnTest"
scenario("allay")
if T == "V":
    sv("op KilnTest", show=False)
alive_auto(a)
sv("gamerule spawn_mobs false", show=False); sv("gamerule mob_griefing true", show=False); sv("difficulty normal", show=False)
platform(0, 0, 40, 40, y=199, clear=12)
sv("tick unfreeze", show=False)
kill_all()
kit(ME)
sv(f"tp {ME} 20.5 200 20.5", show=False)
time.sleep(2)
sv("tick freeze", show=False)
sv("summon minecraft:allay 22.5 201.5 20.5 {PersistenceRequired:1b,Tags:[\"al\"]}", show=False)
time.sleep(1)
sv("setblock 24 200 20 minecraft:jukebox", show=False)
give(ME, "minecraft:music_disc_13", 1)
a.select("minecraft:music_disc_13")
a.lookat(24.5, 200.5, 20.5)
time.sleep(0.6)
a.mouse("right", "tap")
time.sleep(1.5)
F("jukebox:", sv("data get block 24 200 20", show=False, wait=0.5)[-160:])
sv("tick step 10", show=False, wait=1.5)
time.sleep(2)
F("allay nbt:", nbt_of("@e[tag=al,limit=1]", "", 0.5)[:700])
F("dancing / cooldown:", nbt_of("@e[tag=al,limit=1]", "DuplicationCooldown"), nbt_of("@e[tag=al,limit=1]", "CanDuplicate"))
al = ents_of(a, "allay", 20)
F("client sees allays:", len(al))
if al: F("entdata:", a.cmd(f"entdata {al[0]['id']}")[:300])
if al:
    eid = al[0]["id"]
    give(ME, "minecraft:amethyst_shard", 8)
    rec_start(a)
    ok = use_on_entity(a, eid, "minecraft:amethyst_shard")
    time.sleep(2.0)
    F("amethyst shard on allay (1st): click", ok, "shards left", a.inv().get("minecraft:amethyst_shard", 0), "allays", len(ents_of(a, "allay", 20)))
    ls = json.loads(a.cmd("spylog clear"))
    F("lines:", sorted(set(re.sub(r"-?\d+\.\d+(E-?\d+)?", "#", l)[:90] for l in ls if "sound" in l or "particle" in l or "entity_event" in l))[:14])
    F("after: cooldown", nbt_of("@e[tag=al,limit=1]", "DuplicationCooldown"))
    # second shard right away: still on cooldown
    ok2 = use_on_entity(a, eid, "minecraft:amethyst_shard")
    time.sleep(1.5)
    F("2nd shard: click", ok2, "shards left", a.inv().get("minecraft:amethyst_shard", 0), "allays", len(ents_of(a, "allay", 20)))
    # no music: after breaking the jukebox the allay does not dance
    sv("setblock 24 200 20 minecraft:air", show=False)
    sv("data merge entity @e[tag=al,limit=1] {DuplicationCooldown:0L}", show=False, wait=0.5)
    time.sleep(3)
    ok3 = use_on_entity(a, eid, "minecraft:amethyst_shard")
    time.sleep(1.5)
    F("no music, cooldown reset: shards left", a.inv().get("minecraft:amethyst_shard", 0), "allays", len(ents_of(a, "allay", 20)))
    # holding items: give it an item (copper ingot) and see whether it keeps it
    give(ME, "minecraft:iron_ingot", 3)
    ok4 = use_on_entity(a, eid, "minecraft:iron_ingot")
    time.sleep(1.0)
    F("iron ingot to allay: click", ok4, "ingots left", a.inv().get("minecraft:iron_ingot", 0), "allay hand:", nbt_of("@e[tag=al,limit=1]", "HandItems")[:120])
sv("tick unfreeze", show=False)
kill_all()

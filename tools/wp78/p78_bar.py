"""wp78: boss bars when the boss goes away without a fight: /kill, far tp of the player, dimension change."""
from lock import *
respawn_all()
CL = {"K": C(25999), "V": C(26000)}
def bars():
    return {t: CL[t].cmd("bossbars")[:150] for t in "KV"}
both_("gamemode creative KilnTest")
both_("execute in minecraft:overworld run tp KilnTest 500 205 500")
time.sleep(4)
both_("kill @e[type=!player]")
time.sleep(1)
print("start", bars())
both_("summon minecraft:wither 505 205 505 {NoAI:1b,Invul:0}")
time.sleep(2)
print("wither summoned", bars())
both_("kill @e[type=wither]")
time.sleep(2)
print("after /kill", bars())
both_("summon minecraft:wither 505 205 505 {NoAI:1b,Invul:0}")
time.sleep(2)
both_("execute in minecraft:the_nether run tp KilnTest 0 100 0")
time.sleep(6)
print("after dimension change (nether)", bars())
both_("execute in minecraft:overworld run tp KilnTest 500 205 500")
time.sleep(5)
print("back", bars())
both_("kill @e[type=wither]")
time.sleep(2)
print("after /kill 2", bars())
both_("summon minecraft:wither 505 205 505 {NoAI:1b,Invul:0}")
time.sleep(2)
both_("tp KilnTest 2000 150 2000")
time.sleep(8)
print("player far away", bars())
both_("tp KilnTest 500 205 500")
time.sleep(5)
print("back near", bars())
both_("kill @e[type=wither]")
time.sleep(2)
print("end", bars())

main_src = '''    /** usage: PackVectors <out dir> <seed> --dimension <key> --name <file name> --at x,z[,w[,h]] ... (target windows in chunks) */
    public static void main(String[] args) throws Exception {
        Path out = Path.of(args[0]).toAbsolutePath();
        long seedArg = Long.parseLong(args[1]);
        String dimension = "minecraft:overworld", name = null;
        List<int[]> windows = new ArrayList<>();
        for (int i = 2; i < args.length; i++) {
            switch (args[i]) {
                case "--dimension" -> dimension = args[++i];
                case "--name" -> name = args[++i];
                case "--at" -> {
                    String[] p = args[++i].split(",");
                    windows.add(new int[] {Integer.parseInt(p[0]), Integer.parseInt(p[1]), p.length > 2 ? Integer.parseInt(p[2]) : 8, p.length > 3 ? Integer.parseInt(p[3]) : (p.length > 2 ? Integer.parseInt(p[2]) : 8)});
                }
                default -> throw new IllegalArgumentException(args[i]);
            }
        }
        Files.createDirectories(out);
        net.minecraft.server.Main.main(new String[] {"--nogui"});
        MinecraftServer server = findServer();
        for (int waited = 0; !server.isReady(); waited++) {
            if (waited > 50 && !server.isRunning()) {
                OUT.println("server failed to start");
                Runtime.getRuntime().halt(2);
            }
            Thread.sleep(100);
        }
        PackVectors fv = new PackVectors(server, dimension);
        if (fv.seed != seedArg) throw new IllegalStateException("server seed " + fv.seed + " != " + seedArg);
        OUT.printf("server ready, seed %d, structures %b, %s%n", fv.seed, fv.structures, dimension);
        try {
            fv.writePack(out.resolve("pack_" + (name != null ? name : dimension.replace(':', '_').replace('/', '_')) + ".bin"), windows);
        } catch (Throwable e) {
            e.printStackTrace(OUT);
            Runtime.getRuntime().halt(1);
        }
        Runtime.getRuntime().halt(0);
    }
}
'''

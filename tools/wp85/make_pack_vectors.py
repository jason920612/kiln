new_methods = '''
    // ---- wp85: the pack tests' dump -------------------------------------------------------------

    byte[] biomeCells(ProtoChunk chunk, List<String> names) {
        Registry<Biome> biomeRegistry = registries.lookupOrThrow(Registries.BIOME);
        ByteBuffer buf = ByteBuffer.allocate(sections() * 64 * 2).order(ByteOrder.LITTLE_ENDIAN);
        for (int s = 0; s < sections(); s++) {
            LevelChunkSection section = chunk.getSection(s);
            for (int i = 0; i < 64; i++) {
                Holder<Biome> b = section.getNoiseBiome(i & 3, i >> 4, (i >> 2) & 3);
                String name = biomeRegistry.getKey(b.value()).toString();
                int index = names.indexOf(name);
                if (index < 0) {
                    names.add(name);
                    index = names.size() - 1;
                }
                buf.putShort((short) index);
            }
        }
        return buf.array();
    }

    /** pack_<name>.bin: "KWGP", 1, seed, structures, block state count, min y, height, then the regions (target windows). */
    void writePack(Path path, List<int[]> windows) throws Exception {
        int threads = Math.max(1, Runtime.getRuntime().availableProcessors() - 2);
        ExecutorService pool = Executors.newFixedThreadPool(threads);
        try (OutputStream file = new BufferedOutputStream(Files.newOutputStream(path), 1 << 20)) {
            DataOutputStream w = new DataOutputStream(file);
            w.write("KWGP".getBytes(StandardCharsets.US_ASCII));
            w.writeInt(Integer.reverseBytes(1));
            w.writeLong(Long.reverseBytes(seed));
            w.writeInt(Integer.reverseBytes(structures ? 1 : 0));
            w.writeInt(Integer.reverseBytes(Block.BLOCK_STATE_REGISTRY.size()));
            w.writeInt(Integer.reverseBytes(minY()));
            w.writeInt(Integer.reverseBytes(level.getHeight()));
            w.writeInt(Integer.reverseBytes(windows.size()));
            Registry<Structure> structureRegistry = registries.lookupOrThrow(Registries.STRUCTURE);
            for (int[] win : windows) {
                List<int[]> targets = new ArrayList<>();
                for (int dz = 0; dz < win[3]; dz++) for (int dx = 0; dx < win[2]; dx++) targets.add(new int[] {win[0] + dx, win[1] + dz});
                List<long[]> order = decorationOrder(targets);
                Map<Long, ProtoChunk> chunks = terrainFor(order, pool);
                for (long[] d : order) {
                    ProtoChunk chunk = chunks.get(ChunkPos.pack((int) d[1], (int) d[2]));
                    HarnessRegion region = region(chunk, chunks);
                    generator.applyBiomeDecoration(region, chunk, level.structureManager().forWorldGenRegion(region));
                    chunk.setPersistedStatus(ChunkStatus.FEATURES);
                }
                List<String> names = new ArrayList<>();
                List<byte[]> blocks = new ArrayList<>(), cells = new ArrayList<>();
                for (int[] t : targets) {
                    ProtoChunk chunk = chunks.get(ChunkPos.pack(t[0], t[1]));
                    blocks.add(deflate(blocks(chunk)));
                    cells.add(deflate(biomeCells(chunk, names)));
                }
                w.writeInt(Integer.reverseBytes(names.size()));
                for (String n : names) str(w, n);
                w.writeInt(Integer.reverseBytes(targets.size()));
                for (int i = 0; i < targets.size(); i++) {
                    int[] t = targets.get(i);
                    ProtoChunk chunk = chunks.get(ChunkPos.pack(t[0], t[1]));
                    w.writeInt(Integer.reverseBytes(t[0]));
                    w.writeInt(Integer.reverseBytes(t[1]));
                    w.writeInt(Integer.reverseBytes(blocks.get(i).length));
                    w.write(blocks.get(i));
                    w.writeInt(Integer.reverseBytes(cells.get(i).length));
                    w.write(cells.get(i));
                    // The structure starts of the chunk (id and saved NBT), sorted by id.
                    var context = net.minecraft.world.level.levelgen.structure.pieces.StructurePieceSerializationContext.fromLevel(level);
                    List<String> ids = new ArrayList<>();
                    Map<String, byte[]> startTags = new HashMap<>();
                    for (var e : chunk.getAllStarts().entrySet()) {
                        String id = structureRegistry.getKey(e.getKey()).toString();
                        ByteArrayOutputStream nbt = new ByteArrayOutputStream();
                        net.minecraft.nbt.NbtIo.write(e.getValue().createTag(context, chunk.getPos()), new DataOutputStream(nbt));
                        ids.add(id);
                        startTags.put(id, nbt.toByteArray());
                    }
                    ids.sort(null);
                    w.writeInt(Integer.reverseBytes(ids.size()));
                    for (String id : ids) {
                        str(w, id);
                        w.writeInt(Integer.reverseBytes(startTags.get(id).length));
                        w.write(startTags.get(id));
                    }
                }
                OUT.printf("  window %d,%d %dx%d: %d decorated, %d terrain chunks%n", win[0], win[1], win[2], win[3], order.size(), chunks.size());
            }
            w.flush();
        } finally {
            pool.shutdown();
        }
    }
'''

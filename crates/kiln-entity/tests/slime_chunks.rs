//! `Slime.checkSlimeSpawnRules`' slime chunks (`WorldgenRandom.seedSlimeChunk(x, z, seed, 987234911).nextInt(10) == 0`) against the chunks
//! vanilla 26.3 itself reports (tools/wp72/SlimeChunks.java) for |x|, |z| <= 10, for three seeds (a negative one and one that does not fit an int).

use kiln_entity::mob::kinds::slime::is_slime_chunk;

fn check(seed: i64, chunks: &[(i32, i32)]) {
    for x in -10..=10 {
        for z in -10..=10 {
            assert_eq!(is_slime_chunk(seed, x, z), chunks.contains(&(x, z)), "seed {seed} chunk {x} {z}");
        }
    }
    assert!(chunks.len() > 20, "about one chunk in ten");
}

